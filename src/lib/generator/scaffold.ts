/**
 * Project scaffolding.
 *
 * Dependency hoisting
 * -------------------
 * A generated project is a *real* Next.js project — its own `package.json`,
 * `tsconfig.json`, `next.config.mjs`, `postcss.config.mjs`, `app/`, and
 * `components/` — but it does not run `npm install`. `next`, `react`, `react-dom`
 * and `tailwindcss` resolve from the repository root's `node_modules` because
 * Node walks up the directory tree, and the build is invoked as
 * `<repo>/node_modules/.bin/next build` with the generated project as cwd.
 *
 * This is what makes a generation take ~15s instead of ~3 minutes, and it is why
 * the pipeline is viable on free models. The trade-off is stated plainly in
 * docs/architecture.md: a generated project is runnable here, not necessarily
 * runnable after being copied somewhere else without an install.
 */

