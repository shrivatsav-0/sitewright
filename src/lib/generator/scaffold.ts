/** Write a file only when the content changed, so rebuilds stay fast. */
async function writeIfChanged(abs: string, contents: string): Promise<boolean> {
  try {
    const existing = await fsp.readFile(abs, "utf8");
    if (existing === contents) return false;
  } catch {
    /* new file */
  }
  await fsp.mkdir(path.dirname(abs), { recursive: true });
  await fsp.writeFile(abs, contents, "utf8");
  return true;
}

export interface ScaffoldResult {
  projectDir: string;
  written: number;
  changed: number;
}

export async function scaffoldProject(args: {
  projectDir: string;
  files: ScaffoldFile[];
  clean?: boolean;
}): Promise<ScaffoldResult> {
  const { projectDir, files } = args;
  if (args.clean) {
    await fsp.rm(path.join(projectDir, "app"), { recursive: true, force: true });
    await fsp.rm(path.join(projectDir, "components"), { recursive: true, force: true });
    await fsp.rm(path.join(projectDir, "lib"), { recursive: true, force: true });
  }
  await fsp.mkdir(projectDir, { recursive: true });
  let changed = 0;
  for (const f of files) {
    const abs = path.join(projectDir, f.rel);
    if (await writeIfChanged(abs, f.contents)) changed++;
  }
  log.debug("scaffold written", { files: files.length, changed });
  return { projectDir, written: files.length, changed };
}
